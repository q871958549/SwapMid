import { test } from 'node:test'
import assert from 'node:assert/strict'
import { formatGeneratedIndex } from './format-generated-index.mjs'

const raw = `// This file is auto-generated by @hey-api/openapi-ts

export type { ClientOptions, FooDto, BarDto } from './types.gen';
`

test('单行导出拆为一行一个名字，顺序不变', () => {
  assert.equal(formatGeneratedIndex(raw), `// This file is auto-generated by @hey-api/openapi-ts

export type {
  ClientOptions,
  FooDto,
  BarDto,
} from './types.gen';
`)
})

test('幂等：已格式化的文本原样返回', () => {
  const once = formatGeneratedIndex(raw)
  assert.equal(formatGeneratedIndex(once), once)
})

test('非 type 导出同样处理', () => {
  assert.equal(formatGeneratedIndex(`export { a, b } from './sdk.gen';`), `export {\n  a,\n  b,\n} from './sdk.gen';`)
})

test('两侧在不同位置各加一个名字时，多行格式可被 git 按行合并', async () => {
  const { spawnSync } = await import('node:child_process')
  const { mkdtempSync, writeFileSync, readFileSync } = await import('node:fs')
  const { tmpdir } = await import('node:os')
  const { join } = await import('node:path')
  const dir = mkdtempSync(join(tmpdir(), 'fmt-index-'))
  const names = Array.from({ length: 20 }, (_, i) => `T${String(i).padStart(2, '0')}`)
  const src = (list) => formatGeneratedIndex(`export type { ${list.join(', ')} } from './types.gen';\n`)
  const ours = [...names.slice(0, 3), 'T02a', ...names.slice(3)]
  const theirs = [...names.slice(0, 15), 'T14a', ...names.slice(15)]
  writeFileSync(join(dir, 'base'), src(names))
  writeFileSync(join(dir, 'ours'), src(ours))
  writeFileSync(join(dir, 'theirs'), src(theirs))
  const r = spawnSync('git', ['merge-file', join(dir, 'ours'), join(dir, 'base'), join(dir, 'theirs')])
  assert.equal(r.status, 0)
  assert.equal(readFileSync(join(dir, 'ours'), 'utf8'), src([...names.slice(0, 3), 'T02a', ...names.slice(3, 15), 'T14a', ...names.slice(15)]))
})
